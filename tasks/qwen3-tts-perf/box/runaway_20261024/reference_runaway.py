"""Runaway rate of the official qwen_tts implementation on repeated SeedTTS EN prompts: each prompt of a
repeat_meta.py meta.lst generated by Qwen3TTSModel.generate_voice_clone at the checkpoint's own sampling defaults (ICL
voice clone with the reference transcript, language Auto, as the served requests run), in batches of the same prompt,
with max_new_tokens 600: a row that reaches 600 frames (48 s) emitted no codec EOS. Writes each request's generated
frames to OUT_JSON.

usage: <venv>/bin/python reference_runaway.py META_LST OUT_JSON --card 2 [--batch 50] [--max-new-tokens 600]

Run in a venv holding qwen-tts 0.1.1's pins (transformers 4.57.3, accelerate 1.12.0) over the image's torch: its talker
does not load under the image's Transformers 5.19.
"""

import argparse
import json
import time
from collections import defaultdict
from pathlib import Path

import torch
from qwen_tts import Qwen3TTSModel

MODEL = "Qwen/Qwen3-TTS-12Hz-1.7B-Base"
SAMPLES_PER_FRAME = 1920


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("meta")
    parser.add_argument("out")
    parser.add_argument("--card", type=int, required=True)
    parser.add_argument("--batch", type=int, default=50)
    parser.add_argument("--max-new-tokens", type=int, default=600)
    args = parser.parse_args()
    model = Qwen3TTSModel.from_pretrained(
        MODEL, device_map=f"cuda:{args.card}", dtype=torch.bfloat16, attn_implementation="sdpa"
    )
    meta_dir = Path(args.meta).parent
    prompts: dict[str, list[tuple[str, str, str, str]]] = defaultdict(list)
    for line in Path(args.meta).read_text(encoding="utf-8").splitlines():
        request_id, ref_text, wav_name, target_text = line.split("|", 3)
        prompts[request_id.rsplit("_r", 1)[0]].append((request_id, ref_text, wav_name, target_text))
    records = []
    for prompt, rows in prompts.items():
        _, ref_text, wav_name, target_text = rows[0]
        clone_prompt = model.create_voice_clone_prompt(ref_audio=str(meta_dir / wav_name), ref_text=ref_text)
        for start in range(0, len(rows), args.batch):
            batch = rows[start : start + args.batch]
            began = time.perf_counter()
            wavs, _ = model.generate_voice_clone(
                text=[target_text] * len(batch), voice_clone_prompt=clone_prompt, max_new_tokens=args.max_new_tokens
            )
            frames = [round(len(wav) / SAMPLES_PER_FRAME) for wav in wavs]
            records += [{"id": row[0], "prompt": prompt, "frames": count} for row, count in zip(batch, frames)]
            runaways = sum(count >= args.max_new_tokens - 1 for count in frames)
            print(
                f"{prompt} rows {start}-{start + len(batch) - 1}: {runaways} reached {args.max_new_tokens} frames, "
                f"median {sorted(frames)[len(frames) // 2]} frames, {time.perf_counter() - began:.0f} s",
                flush=True,
            )
    Path(args.out).write_text(
        json.dumps({"max_new_tokens": args.max_new_tokens, "records": records}, indent=1), encoding="utf-8"
    )


if __name__ == "__main__":
    main()
